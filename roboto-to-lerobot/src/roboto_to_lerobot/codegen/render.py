# Jinja + black plumbing
# ---------------------------------------------------------------------------


def _jinja_env() -> jinja2.Environment:
    try:
        import jinja2
    except ImportError as exc:  # pragma: no cover - exercised via install extras
        raise RenderError(
            "gen-node needs Jinja2, which is not installed. It ships in the "
            "optional codegen extra (live-inference installs skip it): "
            "pip install 'roboto_to_lerobot[codegen]'."
        ) from exc

    env = jinja2.Environment(
        loader=jinja2.PackageLoader("roboto_to_lerobot.codegen", "templates"),
        autoescape=False,
        keep_trailing_newline=True,
        trim_blocks=True,
        lstrip_blocks=True,
    )
    return env


def _render_template(context: dict[str, Any]) -> str:
    template = _jinja_env().get_template("rclpy.py.j2")
    return template.render(**context)


def _maybe_format_with_black(source: str) -> str:
    """Reformat with black if installed; otherwise return source unchanged.

    Black is an optional codegen dep — codegen output is valid Python
    without it, so users who only install the runtime kernel can
    still inspect generated files. CI installs the dev extra so the bit-
    stable formatted output is what reviewers see.
    """
    try:
        import black  # type: ignore
    except ImportError:
        return source

    mode = black.Mode(line_length=100, target_versions={black.TargetVersion.PY312})
    return black.format_str(source, mode=mode)
